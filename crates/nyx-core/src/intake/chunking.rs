//! Text chunking for the embedding pipeline. Exact port of `chunking.service.ts`.
//!
//! Splits text into overlapping chunks, preferring a paragraph boundary (`\n\n`), then a sentence
//! boundary (`[.!?]` followed by whitespace), then a space, in the back half of each window.
//!
//! Parity notes:
//! - Offsets are UTF-16 code units, like JavaScript's `String.length`/`slice`, so sizes agree with
//!   the TypeScript for every input. A cut that lands inside a surrogate pair yields U+FFFD
//!   (JavaScript would keep a lone surrogate).
//! - `trim()` and `\s` use the JavaScript whitespace set (which includes U+FEFF and excludes
//!   U+0085), not Rust's.
//! - Quirk preserved on purpose: after the window that reaches the end of the text, the TS loop
//!   keeps advancing by `size - overlap` and therefore emits up to `overlap` short trailing
//!   chunks that are suffixes of the last chunk. Set [`ChunkOptions::drop_covered_tail`] to stop
//!   at the first window that reaches the end. The default keeps TS behaviour; golden fixtures
//!   (`fixtures/chunking_golden.json`) were generated by running the TypeScript.

use crate::error::{Error, Result};
use crate::model::{DocChunk, NewDocChunk};
use crate::store::ChunkRepo;

/// Default maximum chunk size in characters (~500 tokens).
pub const DEFAULT_CHUNK_SIZE: usize = 2000;
/// Default overlap in characters (~50 tokens).
pub const DEFAULT_OVERLAP: usize = 200;

/// Chunking parameters.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ChunkOptions {
    /// Approximate max UTF-16 units per chunk.
    pub chunk_size: usize,
    /// Overlap between consecutive chunks.
    pub overlap: usize,
    /// Stop after the window that reaches the end of the text (deviates from the TS; see module docs).
    pub drop_covered_tail: bool,
}

impl Default for ChunkOptions {
    fn default() -> Self {
        Self {
            chunk_size: DEFAULT_CHUNK_SIZE,
            overlap: DEFAULT_OVERLAP,
            drop_covered_tail: false,
        }
    }
}

/// JavaScript `String.prototype.trim` / regex `\s` whitespace.
fn is_js_ws(u: u16) -> bool {
    matches!(
        u,
        0x09..=0x0D
            | 0x20
            | 0xA0
            | 0x1680
            | 0x2000..=0x200A
            | 0x2028
            | 0x2029
            | 0x202F
            | 0x205F
            | 0x3000
            | 0xFEFF
    )
}

fn trim_js(s: &[u16]) -> &[u16] {
    let start = s.iter().position(|&u| !is_js_ws(u)).unwrap_or(s.len());
    let end = s
        .iter()
        .rposition(|&u| !is_js_ws(u))
        .map_or(start, |i| i + 1);
    &s[start..end]
}

fn last_index_of(hay: &[u16], needle: &[u16]) -> Option<usize> {
    if needle.len() > hay.len() {
        return None;
    }
    (0..=hay.len() - needle.len())
        .rev()
        .find(|&i| &hay[i..i + needle.len()] == needle)
}

/// Port of `findBreakPoint`; `start`/`end` index `content`.
fn find_break_point(content: &[u16], start: usize, end: usize) -> usize {
    let window = &content[start..end];
    let half = window.len() / 2;

    if let Some(p) = last_index_of(window, &[0x0A, 0x0A]) {
        if p > half {
            return start + p + 2;
        }
    }

    // Last `[.!?]\s` match whose index is past the half point.
    let mut last_sentence: Option<usize> = None;
    let mut i = 0;
    while i + 1 < window.len() {
        if matches!(window[i], 0x2E | 0x21 | 0x3F) && is_js_ws(window[i + 1]) {
            if i > half {
                last_sentence = Some(i);
            }
            i += 2;
        } else {
            i += 1;
        }
    }
    if let Some(p) = last_sentence {
        return start + p + 2;
    }

    if let Some(p) = window.iter().rposition(|&u| u == 0x20) {
        if p > half {
            return start + p + 1;
        }
    }
    end
}

/// Split `content` into overlapping chunks. Whitespace-only input yields no chunks; input that
/// fits in one chunk is returned untouched (not trimmed).
#[must_use]
pub fn chunk_text(content: &str, options: &ChunkOptions) -> Vec<String> {
    if content.trim_matches(|c: char| is_js_ws_char(c)).is_empty() {
        return Vec::new();
    }
    let units: Vec<u16> = content.encode_utf16().collect();
    let len = units.len();
    if len <= options.chunk_size {
        return vec![content.to_string()];
    }

    let mut chunks = Vec::new();
    let mut start = 0usize;
    while start < len {
        let mut end = (start + options.chunk_size).min(len);
        if end < len {
            end = find_break_point(&units, start, end);
        }
        let chunk = trim_js(&units[start..end]);
        if !chunk.is_empty() {
            chunks.push(String::from_utf16_lossy(chunk));
        }
        if options.drop_covered_tail && end >= len {
            break;
        }
        let advance = end as i64 - start as i64 - options.overlap as i64;
        start += usize::try_from(advance.max(1)).unwrap_or(1);
    }
    chunks
}

fn is_js_ws_char(c: char) -> bool {
    let mut b = [0u16; 2];
    let u = c.encode_utf16(&mut b);
    u.len() == 1 && is_js_ws(u[0])
}

/// Optional embeddings for [`store_doc_chunks`]: model name plus one vector per chunk.
#[derive(Debug, Clone, Copy)]
pub struct Embeddings<'a> {
    /// Embedding model recorded with each vector.
    pub model: &'a str,
    /// One vector per chunk, same order as the chunks.
    pub vectors: &'a [Vec<f32>],
}

/// Chunk `text` and replace the stored chunks of `(doc_id, version)` via [`ChunkRepo`].
///
/// Embeddings are computed by the caller (any provider); pass them as [`Embeddings`] or `None` to
/// store text-only chunks that can be embedded later. Call inside a transaction so the replace
/// is atomic.
pub fn store_doc_chunks(
    repo: &impl ChunkRepo,
    doc_id: &str,
    org_id: &str,
    version: i64,
    text: &str,
    options: &ChunkOptions,
    embeddings: Option<Embeddings<'_>>,
) -> Result<Vec<DocChunk>> {
    let chunks = chunk_text(text, options);
    if let Some(e) = &embeddings {
        if e.vectors.len() != chunks.len() {
            return Err(Error::Invalid(format!(
                "expected {} embeddings, got {}",
                chunks.len(),
                e.vectors.len()
            )));
        }
    }
    let rows: Vec<NewDocChunk> = chunks
        .into_iter()
        .enumerate()
        .map(|(i, content)| NewDocChunk {
            doc_id: doc_id.to_string(),
            org_id: org_id.to_string(),
            content,
            embedding: embeddings.as_ref().map(|e| e.vectors[i].clone()),
            embedding_model: embeddings.as_ref().map(|e| e.model.to_string()),
            version,
            chunk_index: i64::try_from(i).unwrap_or(i64::MAX),
        })
        .collect();
    repo.replace_doc_chunks(doc_id, version, &rows)
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)]
mod tests {
    use super::*;
    use serde_json::Value;

    fn opts(size: usize, overlap: usize) -> ChunkOptions {
        ChunkOptions {
            chunk_size: size,
            overlap,
            drop_covered_tail: false,
        }
    }

    #[test]
    fn matches_typescript_golden_output() {
        let golden: Value =
            serde_json::from_str(include_str!("fixtures/chunking_golden.json")).unwrap();
        for (name, case) in golden.as_object().unwrap() {
            let input = case["input"].as_str().unwrap();
            let o = match case["opts"].as_object() {
                None => ChunkOptions::default(),
                Some(o) => opts(
                    o["chunkSize"].as_u64().unwrap() as usize,
                    o["overlap"].as_u64().unwrap() as usize,
                ),
            };
            let expected: Vec<String> = case["chunks"]
                .as_array()
                .unwrap()
                .iter()
                .map(|v| v.as_str().unwrap().to_string())
                .collect();
            assert_eq!(chunk_text(input, &o), expected, "case {name}");
        }
    }

    #[test]
    fn empty_and_short_input() {
        assert!(chunk_text("", &ChunkOptions::default()).is_empty());
        assert!(chunk_text(" \n\t\u{feff}", &ChunkOptions::default()).is_empty());
        assert_eq!(
            chunk_text("  hi  ", &ChunkOptions::default()),
            vec!["  hi  "]
        );
    }

    #[test]
    fn prefers_paragraph_boundaries() {
        let text = format!("{}\n\n{}", "a".repeat(30), "b".repeat(30));
        let c = chunk_text(&text, &opts(40, 0));
        assert_eq!(c[0], "a".repeat(30));
        assert_eq!(c[1], "b".repeat(30));
    }

    #[test]
    fn zero_overlap_tiles_the_text() {
        let c = chunk_text(&"abcdefghij".repeat(5), &opts(20, 0));
        assert_eq!(
            c.iter().map(String::len).collect::<Vec<_>>(),
            vec![20, 20, 10]
        );
    }

    #[test]
    fn degenerate_sizes_terminate() {
        let _ = chunk_text(&"x".repeat(50), &opts(0, 5));
        let _ = chunk_text(&"x ".repeat(50), &opts(10, 50));
    }

    #[test]
    fn drop_covered_tail_removes_the_overlap_suffix_chunks() {
        let text = "word ".repeat(30);
        let parity = chunk_text(&text, &opts(40, 10));
        let o = ChunkOptions {
            drop_covered_tail: true,
            ..opts(40, 10)
        };
        let fixed = chunk_text(&text, &o);
        assert!(fixed.len() < parity.len());
        assert_eq!(fixed[..], parity[..fixed.len()]);
    }

    #[test]
    fn astral_characters_count_as_two_units() {
        // 11 emoji = 22 UTF-16 units > 20, so it must split like JavaScript would.
        let text = "😀".repeat(11);
        assert!(chunk_text(&text, &opts(20, 0)).len() > 1);
        assert_eq!(chunk_text(&"😀".repeat(10), &opts(20, 0)).len(), 1);
    }
}
